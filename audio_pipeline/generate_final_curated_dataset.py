def build_curated_dataset():
    dataset_dir = "audio_pipeline/Punjabi-Conversational-Speech-Corpus"
    data_dir = os.path.join(dataset_dir, "data")
    
    records = []
    total_duration = 0.0
    
    for i in range(1, 92):
        file_name = f"clip_{i:04d}.wav"
        rel_path = f"data/{file_name}"
        full_path = os.path.join(data_dir, file_name)
        
        if not os.path.exists(full_path):
            print(f"⚠️ Warning: Missing audio file: {full_path}")
            continue
            
        sound = AudioSegment.from_wav(full_path)
        dur = round(len(sound) / 1000.0, 2)
        total_duration += dur
        
        raw_text, curated_text = CURATED_MAPPING.get(i, ("", ""))
        
        records.append({
            "file_name": rel_path,
            "transcription": curated_text,
            "raw_transcription": raw_text,
            "duration_seconds": dur,
            "speaker": "Bhai Ranjit Singh (Dhadrianwale)",
            "language": "pa",
            "script": "Gurmukhi",
            "source": "https://www.youtube.com/watch?v=t6wXJUD4p40"
        })
        
    df = pd.DataFrame(records)
    
    # Save CSV and Parquet
    csv_path = os.path.join(dataset_dir, "metadata.csv")
    df.to_csv(csv_path, index=False, encoding="utf-8")
    
    parquet_path = os.path.join(dataset_dir, "train.parquet")
    df.to_parquet(parquet_path, index=False)
    
    print(f"✅ Generated {len(df)} curated entries. Total Audio: {round(total_duration/60.0, 2)} minutes.")
    
