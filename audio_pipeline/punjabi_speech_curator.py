def clean_gurmukhi_transcription(text: str) -> str:
    """Normalize and repair raw Punjabi ASR speech transcriptions."""
    if not text:
        return ""
    
    # 1. Unicode NFC normalization
    cleaned = unicodedata.normalize("NFC", text.strip())
    
    # 2. Sequential rule-based corrections
    for pattern, replacement in PHONETIC_REPLACEMENTS:
        cleaned = re.sub(pattern, replacement, cleaned)
        
    # 3. Clean up loose vowel signs / diacritics
    cleaned = re.sub(r"\s+([ਾਿੀੁੂੇੈੋੌਂੰੱ])", r"\1", cleaned)
    cleaned = re.sub(r"\bਿਚ\b", "ਵਿੱਚ", cleaned)
    cleaned = re.sub(r"\bਿੱਚ\b", "ਵਿੱਚ", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    
    # 4. Standard Gurmukhi punctuation at sentence end
    if cleaned and not cleaned.endswith(("।", "?", "!")):
        cleaned += "।"
        
    return cleaned

